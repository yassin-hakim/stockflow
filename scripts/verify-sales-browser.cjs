// Run with playwright-cli run-code --filename=scripts/verify-sales-browser.cjs.
// Uses only unique fixtures and an isolated browser session on the current UI.
async (page) => {
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  const runId = Date.now().toString(36);
  const evidence = { runId, url: 'http://localhost:4200', cases: [], requests: [], injectedLostResponses: [] };
  check(await page.evaluate(() => sessionStorage.getItem('stockflow:pending-sales:v1')) === null, 'Use an isolated browser session or resolve its existing pending command first.');
  await page.evaluate(() => { sessionStorage.removeItem('stockflow:pos-draft:v1'); });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => {
    if (request.url().includes('/api/')) evidence.requests.push({ method: request.method(), path: new URL(request.url()).pathname, key: request.headers()['idempotency-key'] ?? null });
  });
  const api = async (path, method = 'GET', body, key) => {
    const response = await page.request.fetch(`http://localhost:4200/api${path}`, { method, data: body, headers: key ? { 'Idempotency-Key': key } : {} });
    const data = await response.json();
    check(response.ok(), `${method} ${path}: ${response.status()} ${JSON.stringify(data)}`);
    return data;
  };
  const uuid = () => crypto.randomUUID();
  const locationId = '00000000-0000-4000-8000-000000000001';
  const product = await api('/products', 'POST', { name: `Browser coffee ${runId}`, category: 'Verification', unit: 'kg', lowStockThreshold: 0 });
  await api('/receipts', 'POST', { locationId, reference: `Browser delivery ${runId}`, reason: 'Browser correction acceptance', lines: [{ productId: product.id, quantity: 5, unitCostMinor: 1000 }] }, uuid());
  let menu = await api('/menu-items', 'POST', { name: `Browser espresso ${runId}`, category: 'Verification', currency: 'USD', priceMinor: 500, ingredients: [{ productId: product.id, quantity: 0.1 }] });
  evidence.productId = product.id; evidence.menuItemId = menu.id;
  const viewportCheck = async () => {
    const result = await page.evaluate(() => ({ width: innerWidth, overflow: document.documentElement.scrollWidth > innerWidth, focus: document.activeElement?.id || document.activeElement?.textContent?.trim() }));
    check(!result.overflow, `Horizontal overflow at ${result.width}`); return result;
  };
  const capture = async (name) => { await viewportCheck(); await page.screenshot({ path: `output/playwright/sales-${name}.png`, fullPage: true }); };
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('http://localhost:4200/pos');
  await page.getByLabel('Find menu item').waitFor();
  await page.getByLabel('Consume ingredients from').selectOption(locationId);
  await page.getByLabel('Find menu item').fill(menu.name);
  const add = page.getByRole('button', { name: `Add ${menu.name}`, exact: true });
  await add.focus(); await page.keyboard.press('Enter');
  await page.getByLabel('Item count', { exact: true }).fill('3');
  await page.keyboard.press('Tab');
  await page.getByRole('button', { name: 'Complete sale', exact: true }).waitFor();
  await page.waitForFunction(() => document.querySelector('#reviewed-total')?.textContent?.includes('15.00'));
  const saleId = await page.evaluate(() => sessionStorage.getItem('stockflow:pos-draft:v1'));
  check(saleId, 'Owner-priced draft must be saved.'); evidence.saleId = saleId;
  const reviewed = await api(`/sales/${saleId}`); check(reviewed.totalMinor === 1500, 'Owner-priced total wrong.');
  await capture('pos-reviewed-desktop');
  for (const width of [700, 701, 375]) {
    await page.setViewportSize({ width, height: 900 }); await capture(`pos-reviewed-${width}`);
    evidence.cases.push({ route: '/pos', state: 'reviewed', width, quantity: 3, totalMinor: reviewed.totalMinor, ...(await viewportCheck()) });
  }
  // Actual BFF processes the command; only its response is lost in this browser.
  const checkoutPattern = `**/api/sales/${saleId}/checkout`;
  await page.route(checkoutPattern, async route => {
    const response = await route.fetch();
    const data = await response.json(); check(data.status === 'COMPLETED', 'Lost checkout must actually commit.');
    evidence.injectedLostResponses.push({ kind: 'CHECKOUT', key: route.request().headers()['idempotency-key'], statusOnServer: data.status });
    await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { code: 'SERVICE_UNAVAILABLE', message: 'Injected lost committed checkout response.' } }) });
  }, { times: 1 });
  await page.getByRole('button', { name: 'Complete sale', exact: true }).focus(); await page.keyboard.press('Enter');
  await page.getByRole('heading', { name: 'Sale outcome needs confirmation' }).waitFor();
  await page.getByRole('alert').filter({ hasText: 'Injected lost committed checkout response.' }).waitFor();
  await page.waitForFunction(() => !Array.from(document.querySelectorAll('button')).find(node => node.textContent.trim() === 'Check saved sale status')?.disabled);
  check(await page.getByLabel('Item count', { exact: true }).isDisabled(), 'Uncertain checkout must lock cart.');
  const savedCheckout = await page.evaluate(() => JSON.parse(sessionStorage.getItem('stockflow:pending-sales:v1')));
  check(savedCheckout.kind === 'CHECKOUT', 'Missing saved original checkout identity.');
  await capture('pos-uncertain-mobile');
  await page.reload();
  await page.getByRole('link', { name: 'Open receipt', exact: true }).waitFor();
  check(await page.evaluate(() => sessionStorage.getItem('stockflow:pending-sales:v1')) === null, 'Recovered checkout key must clear.');
  evidence.cases.push({ route: '/pos', state: 'lost-response-reload-recovered', width: 375, originalKey: savedCheckout.key, lockedBeforeReload: true, serverStatus: 'COMPLETED', recoveredStatus: 'COMPLETED' });
  await page.getByRole('link', { name: 'Open receipt', exact: true }).focus(); await page.keyboard.press('Enter');
  await page.getByRole('heading', { name: 'StockFlow receipt' }).waitFor();
  const originalReceipt = await api(`/sales/${saleId}/receipt`);
  await capture('receipt-mobile');
  await page.setViewportSize({ width: 1440, height: 1000 }); await capture('receipt-desktop');
  await page.emulateMedia({ media: 'print' });
  check(await page.getByRole('button', { name: 'Print receipt' }).isHidden(), 'Print action must hide in print.');
  check(await page.getByRole('heading', { name: 'StockFlow receipt' }).isVisible(), 'Receipt must remain printable.');
  await page.pdf({ path: 'output/playwright/sales-receipt-print.pdf', format: 'A4', printBackground: true });
  await page.screenshot({ path: 'output/playwright/sales-receipt-print.png', fullPage: true });
  await page.emulateMedia({ media: 'screen' });
  evidence.cases.push({ route: `/sales/${saleId}/receipt`, state: 'print', totalMinor: originalReceipt.totalMinor, actionsHidden: true });
  menu = await api(`/menu-items/${menu.id}/publish`, 'POST', { expectedVersion: menu.version, name: menu.name, category: menu.category, currency: 'USD', priceMinor: 900, ingredients: [{ productId: product.id, quantity: 0.4 }] });
  await page.goto(`http://localhost:4200/sales/${saleId}/refunds/new`);
  await page.getByRole('heading', { name: 'Refund items' }).waitFor();
  check(!(await page.getByRole('checkbox', { name: 'Return original ingredients to stock' }).isChecked()), 'No-restock must be the default.');
  await page.getByRole('button', { name: 'Record refund', exact: true }).focus(); await page.keyboard.press('Enter');
  await page.getByRole('alert').filter({ hasText: 'Select eligible whole item quantities' }).waitFor();
  check((await api(`/sales/${saleId}/refunds`)).items.length === 0, 'Invalid correction must not dispatch.');
  await page.getByLabel('Refund count', { exact: true }).fill('1');
  await page.getByLabel('Reason', { exact: true }).fill('Partial correction with no physical ingredient return');
  await page.getByRole('checkbox', { name: 'I reviewed the quantities and stock-return choice.' }).focus(); await page.keyboard.press('Space');
  const refundPattern = `**/api/sales/${saleId}/refunds`;
  await page.route(refundPattern, async route => {
    if (route.request().method() !== 'POST') { await route.continue(); return; }
    const response = await route.fetch(), data = await response.json(); check(data.status === 'COMPLETED', 'Lost refund must actually commit.');
    evidence.injectedLostResponses.push({ kind: 'REFUND', key: route.request().headers()['idempotency-key'], statusOnServer: data.status });
    await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { code: 'SERVICE_UNAVAILABLE', message: 'Injected lost committed refund response.' } }) });
  }, { times: 1 });
  await page.keyboard.press('Tab');
  check(await page.getByRole('button', { name: 'Record refund', exact: true }).evaluate(node => node === document.activeElement), 'Confirmation Tab should reach submit.');
  await page.keyboard.press('Enter');
  await page.getByRole('heading', { name: 'A correction needs confirmation' }).waitFor();
  check(await page.getByLabel('Refund count', { exact: true }).isDisabled(), 'Uncertain refund must lock correction.');
  const savedRefund = await page.evaluate(() => JSON.parse(sessionStorage.getItem('stockflow:pending-sales:v1')));
  check(savedRefund.kind === 'REFUND' && savedRefund.key !== savedCheckout.key, 'Refund needs its own original key.');
  await capture('refund-uncertain-desktop');
  await page.setViewportSize({ width: 375, height: 900 }); await capture('refund-uncertain-mobile');
  await page.reload(); await page.getByRole('heading', { name: 'A correction needs confirmation' }).waitFor();
  check((await page.evaluate(() => JSON.parse(sessionStorage.getItem('stockflow:pending-sales:v1')))).key === savedRefund.key, 'Reload changed original refund key.');
  await page.getByRole('button', { name: 'Check correction status' }).focus(); await page.keyboard.press('Enter');
  await page.getByText('Refund recorded: $5.00.', { exact: false }).waitFor();
  check(await page.evaluate(() => sessionStorage.getItem('stockflow:pending-sales:v1')) === null, 'Terminal correction key must clear.');
  check((await api(`/inventory/${product.id}`)).quantity === 4.7, 'No-restock partial correction changed stock.');
  await capture('refund-partial-mobile');
  evidence.cases.push({ route: `/sales/${saleId}/refunds/new`, state: 'partial-no-restock-lost-response-recovery', width: 375, originalKey: savedRefund.key, amountMinor: 500, retainedOnReload: true, lockedPending: true, balance: 4.7 });
  await page.getByLabel('Refund count', { exact: true }).fill('2');
  await page.getByLabel('Reason', { exact: true }).fill('Return all remaining original ingredients');
  await page.getByRole('checkbox', { name: 'Return original ingredients to stock' }).focus(); await page.keyboard.press('Space');
  await page.getByRole('heading', { name: 'Ingredients to return' }).waitFor();
  check((await page.locator('app-sale-refund').innerText()).includes(`0.2 kg ${product.name}`), 'Return preview must use original recipe.');
  await page.getByRole('checkbox', { name: 'I reviewed the quantities and stock-return choice.' }).focus(); await page.keyboard.press('Space');
  await capture('refund-full-reviewed-mobile');
  await page.keyboard.press('Tab'); await page.keyboard.press('Enter');
  await page.getByText('Refund recorded: $10.00.', { exact: false }).waitFor();
  await page.getByText('0 refundable of 3 sold', { exact: false }).waitFor();
  await capture('refund-full-mobile');
  await page.setViewportSize({ width: 1440, height: 1000 }); await capture('refund-full-desktop');
  check((await api(`/inventory/${product.id}`)).quantity === 4.9, 'Full remaining return must restore only original ingredients.');
  const finalSale = await api(`/sales/${saleId}`);
  check(finalSale.refunds.length === 2 && finalSale.refunds.every(refund => refund.status === 'COMPLETED'), 'Duplicate or nonterminal refunds.');
  check(finalSale.refunds.reduce((sum, refund) => sum + refund.amountMinor, 0) === 1500, 'Refund cumulative amount incorrect.');
  check(JSON.stringify(await api(`/sales/${saleId}/receipt`)) === JSON.stringify(originalReceipt), 'Receipt changed after correction.');
  await page.getByLabel('Refund count', { exact: true }).fill('1');
  await page.getByLabel('Reason', { exact: true }).fill('Attempt beyond sold count');
  await page.getByRole('checkbox', { name: 'I reviewed the quantities and stock-return choice.' }).check();
  await page.getByRole('button', { name: 'Record refund', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Select eligible whole item quantities' }).waitFor();
  check((await api(`/sales/${saleId}/refunds`)).items.length === 2, 'Excessive correction dispatched.');
  evidence.cases.push({ route: `/sales/${saleId}/refunds/new`, state: 'full-remaining-explicit-restock', amountMinor: 1000, originalRecipeReturn: 0.2, currentRecipePerItem: 0.4, balance: 4.9, excessBlocked: true, refundCount: 2, receiptUnchanged: true });
  await page.goto(`http://localhost:4200/sales/${saleId}`);
  await page.getByRole('heading', { name: 'Sale detail', exact: true }).waitFor();
  await page.getByText('No ingredient return', { exact: false }).waitFor();
  await capture('detail-desktop');
  await page.setViewportSize({ width: 375, height: 900 }); await capture('detail-mobile');
  evidence.errors = errors; check(errors.length === 0, `Browser errors: ${errors}`);
  evidence.keyboard = 'Enter adds/completes, Space confirms/restocks, Tab reaches submit; recovery uses keyboard.';
  evidence.receiptUnchanged = true; evidence.passed = true;
  await page.evaluate(value => { window.__salesProof = value; }, evidence);
}
